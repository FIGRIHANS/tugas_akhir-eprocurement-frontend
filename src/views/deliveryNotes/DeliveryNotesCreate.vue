const vendorDocUploadError = ref<string>('')
const vendorDocBase64 = ref<string>('')

const triggerVendorDocUpload = () => {
  vendorDocInput.value?.click()
}

const handleVendorDocFile = (file: File) => {
  vendorDocUploadError.value = ''
  const maxSize = 5 * 1024 * 1024 // 5MB
  if (file.size > maxSize) {
    vendorDocUploadError.value = 'File size exceeds 5MB limit.'
    return
  }
  const allowed = ['application/pdf', 'image/png', 'image/jpeg', 'image/jpg']
  if (!allowed.includes(file.type)) {
    vendorDocUploadError.value = 'Only PDF, PNG, JPG files are allowed.'
    return
  }
  vendorDocFile.value = file
  // Convert to base64
  const reader = new FileReader()
  reader.onload = (e) => {
    vendorDocBase64.value = (e.target?.result as string) || ''
  }
  reader.readAsDataURL(file)
}

const handleVendorDocChange = (event: Event) => {
  const input = event.target as HTMLInputElement
  if (input.files && input.files[0]) handleVendorDocFile(input.files[0])
}

const handleVendorDocDrop = (event: DragEvent) => {
  const file = event.dataTransfer?.files[0]
  if (file) handleVendorDocFile(file)
}

const removeVendorDoc = () => {
  vendorDocFile.value = null
  vendorDocBase64.value = ''
  vendorDocUploadError.value = ''
  if (vendorDocInput.value) vendorDocInput.value.value = ''
}

