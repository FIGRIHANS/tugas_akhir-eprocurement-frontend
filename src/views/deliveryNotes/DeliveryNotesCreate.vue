const getValidationResult = (isDraft = false): FormValidationResult => {
  if (isBlank(formData.value.poNumber)) {
    return validationFail('PO Number wajib diisi.', 'po-search')
  }

  if (isBlank(formData.value.vendorCode)) {
    return validationFail('Vendor Code wajib diisi.', 'vendor-code')
  }

  if (!isDraft && isBlank(formData.value.driverName)) {
    return validationFail('Driver Name wajib diisi.', 'driver-name')
  }

  if (!isDraft && isBlank(formData.value.licensePlate)) {
    return validationFail('License Plate wajib diisi.', 'license-plate')
  }

  if (!isDraft && isBlank(formData.value.transporter)) {
    return validationFail('Transporter wajib diisi.', 'transporter')
  }

  if (!isDraft && isBlank(formData.value.pickupAddress)) {
    return validationFail('Pickup Address wajib diisi.', 'pickup-address')
  }

  if (!isDraft && isBlank(formData.value.destinationAddress)) {
    return validationFail('Destination wajib diisi.', 'destination-address')
  }

  if (!isDraft && isBlank(formData.value.estimatedArrival)) {
    return validationFail('Estimated Arrival Date wajib diisi.', 'estimated-arrival')
  }

  if (
    !isDraft &&
    formData.value.estimatedArrival &&
    isDateTimeBeforeToday(formData.value.estimatedArrival)
  ) {
    return validationFail(
      'Estimated Arrival Date tidak boleh sebelum hari ini.',
      'estimated-arrival',
    )
  }

  if (!isDraft && tableData.value.length === 0) {
    return validationFail('Minimal satu item wajib ditambahkan.')
  }

  for (let i = 0; i < tableData.value.length; i++) {
    const item = tableData.value[i]

    if (!isDraft) {
      if (isBlank(item.sku)) {
        return validationFail(`SKU wajib diisi untuk item #${i + 1}.`, `item-${i}-sku`)
      }
      if (isBlank(item.description)) {
        return validationFail(
          `Description wajib diisi untuk item #${i + 1}.`,
          `item-${i}-description`,
        )
      }
      if (isBlank(item.uom)) {
        return validationFail(`UOM wajib diisi untuk item #${i + 1}.`, `item-${i}-uom`)
      }
      if (isBlank(item.lotNo)) {
        return validationFail(`Lot No wajib diisi untuk item #${i + 1}.`, `item-${i}-lot-no`)
      }
    }

    if (!isDraft || item.sku || item.description || item.uom || item.lotNo || item.qtyShipped > 0) {
      const qtyResult = validateQtyShipped(item.qtyShipped, item.qtyOrdered, !isDraft)
      if (!qtyResult.valid && qtyResult.message) {
        return validationFail(`${qtyResult.message} (item #${i + 1})`, `item-${i}-qty-shipped`)
      }
    }
  }

  if (!isDraft && signaturePad.value) {
    const saveResult = signaturePad.value.save()
    if (!saveResult || saveResult.trim().length === 0) {
      return validationFail('Driver Signature wajib diisi.', 'signature')
    }
  }

  return validationOk()
}

const canSaveDraft = computed(() => getValidationResult(true).valid)
const canSubmit = computed(() => getValidationResult(false).valid)

const validateForm = async (isDraft = false): Promise<boolean> => {
  trimFormTextFields()
  const result = getValidationResult(isDraft)
  if (!result.valid) {
    showValidationError(result.message!)
    await focusValidationField(result.focusKey)
    return false
  }
  return true
}

const submitForm = async (isDraft = false) => {
  if (!(await validateForm(isDraft))) return

  isSubmitting.value = true

  try {
    // Save signature data
    let signatureData = ''
    if (signaturePad.value) {
      const saveResult = signaturePad.value.save()
      console.log('Signature save result:', saveResult)
      console.log('Type of save result:', typeof saveResult)

      // vue3-signature returns the Base64 string directly (not an object)
      if (saveResult && saveResult.trim().length > 0) {
        signatureData = saveResult
        console.log('✅ Signature data captured successfully!')
        console.log('Signature data length:', signatureData.length)
        console.log('First 100 chars:', signatureData.substring(0, 100))
      } else {
        console.warn('⚠️ Signature pad is empty - user did not draw anything')
      }
    } else {
      console.error('❌ Signature pad ref is null')
    }

    console.log('Final signature data length:', signatureData?.length || 0)

    // Convert estimatedArrival to shippingDate (YYYY-MM-DD format)
    const shippingDate = formData.value.estimatedArrival
      ? formData.value.estimatedArrival.split('T')[0]
      : new Date().toISOString().split('T')[0]

    // Ensure vendorID always reflects the JWT actor (set during PO selection, refreshed here as safety net)
    // JWT UserId = VendorId for vendor users. Must be sent as a number (int? on the backend).
    const jwtVendorId = getUserIdFromToken()
    const effectiveVendorID: number | undefined = jwtVendorId ?? formData.value.vendorID

    // Prepare payload according to backend structure
    const payload: DeliveryNoteCreatePayload = {
      // Empty string means backend auto-generates the DN number
      deliveryNoteNumber: formData.value.deliveryNoteNumber.trim() || '',
      poNumber: formData.value.poNumber,
      vendorCode: formData.value.vendorCode,
      vendorID: effectiveVendorID,
      vendorName: formData.value.vendorName || selectedPO.value?.vendorName || '',
      tripID: formData.value.tripID || undefined,
      transporter: formData.value.transporter,
      licensePlate: formData.value.licensePlate,
      driverName: formData.value.driverName,
      pickupAddress: formData.value.pickupAddress,
      destinationAddress: formData.value.destinationAddress,
      driverSignature: signatureData || '', // Ensure always included
      truckType: formData.value.truckType || undefined,
      shippingDate: shippingDate,
      status: isDraft ? 'Draft' : 'On Delivery',
      vendorDeliveryDocumentPath: vendorDocBase64.value || undefined,
      details: isDraft
        ? tableData.value.filter(
            (item) => item.sku || item.description || item.uom || item.lotNo || item.qtyShipped > 0,
          )
        : tableData.value,
    }

    console.log('Submitting delivery note:', payload)
    console.log('Signature in payload:', payload.driverSignature ? 'YES' : 'NO (empty)')

    const createdResult = await DeliveryNotesService.create(payload)

    // The service returns result.content which contains the created delivery note data
    const generatedNumber =
      createdResult?.content?.deliveryNoteNumber ||
      createdResult?.deliveryNoteNumber ||
      payload.deliveryNoteNumber ||
      '(auto-generated)'
    notificationModal.value = {
      type: 'success',
      title: 'Success',
      text: isDraft
        ? `Delivery note saved as draft successfully!\nDelivery Note Number: ${generatedNumber}`
        : `Delivery note created successfully!\nDelivery Note Number: ${generatedNumber}`,
    }
    showNotificationModal.value = true

    // Wait before redirect
    await new Promise((resolve) => setTimeout(resolve, 1500))

    router.push({ name: 'deliveryNotesList' })
  } catch (error) {
    console.error('Error submitting form:', error)
    notificationModal.value = {
      type: 'error',
      title: 'Error',
      text: 'Failed to create delivery note. Please try again.',
    }
    showNotificationModal.value = true
  } finally {
    isSubmitting.value = false
  }
}
